import api from "@/lib/axios";
import { AxiosError } from "axios";
import type { CustomerOrder } from "@/lib/orders";

function toError(err: unknown, fallback: string): Error {
  if (err instanceof AxiosError) {
    const msg = (err.response?.data as { message?: string | string[] } | undefined)?.message;
    if (Array.isArray(msg)) return new Error(msg[0] ?? fallback);
    if (typeof msg === "string") return new Error(msg);
  }
  return new Error(fallback);
}

export const ordersApi = {
  async getMyOrders(): Promise<CustomerOrder[]> {
    try {
      const res = await api.get("/orders/my");
      return Array.isArray(res.data) ? res.data : [];
    } catch (err) {
      throw toError(err, "Could not load your orders.");
    }
  },

  async getMyOrder(orderId: string): Promise<CustomerOrder> {
    try {
      const res = await api.get(`/orders/my/${encodeURIComponent(orderId)}`);
      return res.data;
    } catch (err) {
      throw toError(err, "Could not load this order.");
    }
  },

  /** URL of the PDF receipt generated by the backend. */
  receiptPdfUrl(orderId: string): string {
    return `${api.defaults.baseURL}/orders/${encodeURIComponent(orderId)}/receipt`;
  },
};
